// 通用脱敏工具函数
// 学号：只显示前2后2位，中间用*号替代（如 2022****12）
export function maskStudentId(id: string): string {
  if (!id || id.length < 6) return id;
  return id.slice(0, 2) + '*'.repeat(id.length - 4) + id.slice(-2);
}

